let day = "wed";
switch(day){
    case "mon":
        console.log("First day");
        break;
    case "tue":
        console.log("Second day");
        break;
    case "wed":
        console.log("Third day");
        break;
    case "thu":
        console.log("Forth day");
        break;
    case "fri":
        console.log("Fifth day");
        break;
    case "sat":
        console.log("Sixth day");
        break;
    case "sun":
        console.log("Seventh day");
        break;
    default:
        console.log("invalid input");         
        break;           
       
}